RES = []
BJ = ck.BEIJING


def check(c, m, why=""):
    RES.append((bool(c), m))
    print(("  [过]   " if c else "  [没过] ") + m + ("" if c or not why else f"\n           {str(why)[:600]}"))


def at(y, mo, d_, h, mi, tz=BJ):
    return datetime(y, mo, d_, h, mi, tzinfo=tz).timestamp()


def show(ts, tz=BJ):
    return None if ts is None else ck.fmt(ts, tz, "%Y-%m-%d %H:%M")


